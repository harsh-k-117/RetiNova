function options = ...
    makeGpuTrainOptions( ...
        miniBatch, ...
        valData, ...
        stepsPerEpoch, ...
        ckptDir)

common = { ...
    'InitialLearnRate', ...
        1e-4, ...
    'MiniBatchSize', ...
        miniBatch, ...
    'MaxEpochs', ...
        10, ...
    'Shuffle', ...
        'every-epoch', ...
    'ValidationData', ...
        valData, ...
    'ValidationFrequency', ...
        stepsPerEpoch, ...
    'ValidationPatience', ...
        5, ...
    'ExecutionEnvironment', ...
        'gpu', ...
    'Verbose', ...
        true, ...
    'VerboseFrequency', ...
        5, ...
    'Plots', ...
        'none', ...
    'OutputNetwork', ...
        'best-validation-loss', ...
    'CheckpointPath', ...
        ckptDir, ...
    'CheckpointFrequency', ...
        1};

try

    options = ...
        trainingOptions( ...
            'adam', ...
            common{:}, ...
            'CheckpointFrequencyUnit', ...
                'epoch', ...
            'DispatchInBackground', ...
                true);

    return;

catch
end

try

    options = ...
        trainingOptions( ...
            'adam', ...
            common{:}, ...
            'DispatchInBackground', ...
                true);

    return;

catch
end

options = ...
    trainingOptions( ...
        'adam', ...
        common{:});

end

% =========================================================================

function miniBatch = ...
    pickMiniBatchSize( ...
        availableBytes)

gb = ...
    double(availableBytes) / 2^30;

if gb >= 8

    miniBatch = 16;

elseif gb >= 5

    miniBatch = 8;

elseif gb >= 3

    miniBatch = 4;

else

    miniBatch = 2;

end

end

% =========================================================================

function tf = ...
    isGpuMemoryError( ...
        err)

msg = lower( ...
    string(err.message) + ...
    " " + ...
    string(err.identifier));

tf = ...
    contains(msg, "out of memory") || ...
    contains(msg, "oom") || ...
    ( ...
        contains(msg, "gpu") && ...
        contains(msg, "memory"));

end

% =========================================================================

function cachedPaths = ...
    cachePreprocessedImages( ...
        filePaths, ...
        imageNames, ...
        cacheDir, ...
        inputSize)

if ~isfolder(cacheDir)
    mkdir(cacheDir);
end

cachedPaths = ...
    strings(size(filePaths));

fprintf( ...
    'Caching 512 px training images under %s\n', ...
    cacheDir);

for i = 1:numel(filePaths)

    outFile = ...
        fullfile( ...
            cacheDir, ...
            imageNames(i) + ".png");

    cachedPaths(i) = ...
        outFile;

    if isfile(outFile)
        continue;
    end

    rgb = ...
        preprocessIDRiDImage( ...
            filePaths(i), ...
            inputSize, ...
            false);

    imwrite( ...
        rgb, ...
        outFile);

    if mod(i, 25) == 0 || ...
            i == numel(filePaths)

        fprintf( ...
            '  cached %d / %d\n', ...
            i, ...
            numel(filePaths));

    end
end

end

% =========================================================================

function I = ...
    readCachedNormalized( ...
        filename)

pixels = ...
    im2single( ...
        imread(filename));

meanRGB = ...
    reshape( ...
        single([0.485 0.456 0.406]), ...
        1, 1, 3);

stdRGB = ...
    reshape( ...
        single([0.229 0.224 0.225]), ...
        1, 1, 3);

I = ...
    (pixels - meanRGB) ./ stdRGB;

end

% =========================================================================

function rows = ...
    balanceTrainingRows( ...
        sourceRows, ...
        grades, ...
        targetCounts)

% Create a moderately balanced training-row list.
%
% Each class is sampled with replacement until it reaches its target.
%
% The repeated rows are later passed through augmentedImageDatastore,
% so repeated observations receive randomized geometric transformations.

foldGrades = ...
    grades(sourceRows);

rows = ...
    zeros(0, 1);

for grade = 0:4

    classRows = ...
        sourceRows( ...
            foldGrades == grade);

    if isempty(classRows)

        error( ...
            'Cannot sample grade %d because it has no examples.', ...
            grade);

    end

    targetCount = ...
        targetCounts(grade + 1);

    selected = ...
        classRows( ...
            randsample( ...
                numel(classRows), ...
                targetCount, ...
                true));

    rows = ...
        [rows; selected]; %#ok<AGROW>

end

% Shuffle the repeated rows.
rows = ...
    rows( ...
        randperm( ...
            numel(rows)));

end

