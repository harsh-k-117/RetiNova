% TRAINIDRIDGRADER
% Train and cross-validate a five-grade IDRiD diabetic-retinopathy grader.
%
% EXPERIMENT:
%   Augmentation-balanced training WITHOUT class weighting.
%
% Strategy:
%   - 3-fold stratified CV
%   - Inner 15%% split for early stopping
%   - Square-root class balancing by repeated training rows
%   - Random image augmentation applied to repeated rows
%   - NO class-weighted loss
%   - OOF probability collection
%   - OOF ordinal threshold fitting
%   - OOF grade-4 probability threshold fitting
%
% The official 103-image IDRiD test set is NEVER read here.
%
% Requires:
%   Deep Learning Toolbox
%   Image Processing Toolbox
%   Statistics and Machine Learning Toolbox
%   Parallel Computing Toolbox
%   CUDA-capable NVIDIA GPU
%
% Requires preprocessIDRiDImage.m on MATLAB path.

clear;
clc;

rng(42, 'twister');

% =========================================================================
% CONFIGURATION
% =========================================================================

numFolds = 5;

% =========================================================================
% GPU
% =========================================================================

if ~canUseGPU
    error([ ...
        'No CUDA GPU visible to MATLAB. Install Parallel Computing Toolbox ', ...
        'and a supported NVIDIA driver, then run gpuDeviceTable.']);
end

g = gpuDevice;

memGB = double(g.AvailableMemory) / 2^30;

fprintf( ...
    'GPU: %s | compute capability %s | %.2f GB free\n', ...
    string(g.Name), ...
    string(g.ComputeCapability), ...
    memGB);

% =========================================================================
% PATHS
% =========================================================================

projectDir = fileparts(mfilename('fullpath'));

dataRoot = fullfile( ...
    projectDir, ...
    'data', ...
    'B. Disease Grading', ...
    'B. Disease Grading');

archive = fullfile( ...
    projectDir, ...
    'data', ...
    'B. Disease Grading.zip');

trainImageDir = fullfile( ...
    dataRoot, ...
    '1. Original Images', ...
    'a. Training Set');

trainCsv = fullfile( ...
    dataRoot, ...
    '2. Groundtruths', ...
    'a. IDRiD_Disease Grading_Training Labels.csv');

modelDir = fullfile( ...
    projectDir, ...
    'models', ...
    'idrid_grade5');

% =========================================================================
% DATA CHECK
% =========================================================================

if ~isfolder(trainImageDir) || ...
        isempty(dir(fullfile(trainImageDir, '*.jpg')))

    if ~isfile(archive)
        error( ...
            'IDRiD archive not found: %s', ...
            archive);
    end

    unzip( ...
        archive, ...
        fullfile(projectDir, 'data', 'B. Disease Grading'));
end

if ~isfile(trainCsv)

    error( ...
        'Training labels not found: %s', ...
        trainCsv);

end

if ~isfolder(modelDir)
    mkdir(modelDir);
end

warning( ...
    'off', ...
    'MATLAB:table:ModifiedAndSavedVarnames');

% =========================================================================
% LOAD LABELS
% =========================================================================

T = readtable(trainCsv);

imageNames = string(T.ImageName);

rawGrades = double(T.RetinopathyGrade);

n = numel(imageNames);

classNames = string(0:4);

labels = categorical( ...
    string(rawGrades), ...
    classNames);

if any(isundefined(labels)) || n ~= 413

    error( ...
        'Expected 413 IDRiD training rows with grades in 0..4; found %d.', ...
        n);

end

filePaths = fullfile( ...
    trainImageDir, ...
    imageNames + ".jpg");

if any(~isfile(filePaths))

    missing = find(~isfile(filePaths), 1);

    error( ...
        'Image not found: %s', ...
        filePaths(missing));

end

% =========================================================================
% DATASET STATISTICS
% =========================================================================

counts = countcats(labels);

fprintf( ...
    '\nTraining counts, grades 0..4: %s\n', ...
    mat2str(counts'));

inputSize = [512 512 3];

% =========================================================================
% CACHE PREPROCESSED IMAGES
% =========================================================================

cachedPaths = ...
    cachePreprocessedImages( ...
        filePaths, ...
        imageNames, ...
        fullfile(modelDir, 'cache_512'), ...
        inputSize);

% =========================================================================
% BACKBONE
% =========================================================================

[~, backboneName] = ...
    buildGradingNetwork( ...
        inputSize, ...
        projectDir);

fprintf( ...
    'Backbone: %s\n', ...
    backboneName);

% =========================================================================
% FUNDUS AUGMENTATION
%
% Conservative geometric changes.
%
% We deliberately do NOT use reflection for this experiment.
% =========================================================================

augmenter = imageDataAugmenter( ...
    'RandRotation', [-10 10], ...
    'RandScale', [0.95 1.05], ...
    'RandXTranslation', [-8 8], ...
    'RandYTranslation', [-8 8]);

readCached = ...
    @(filename) readCachedNormalized(filename);

imds = imageDatastore( ...
    cachedPaths, ...
    'Labels', ...
        labels, ...
    'ReadFcn', ...
        readCached);

% =========================================================================
% CROSS-VALIDATION
% =========================================================================

cv = cvpartition( ...
    labels, ...
    'KFold', ...
    numFolds);

oofScores = ...
    nan(n, 5);

oofPredictions = ...
    nan(n, 1);

% Record the actual sampling used in each fold.
foldSamplingTargets = ...
    nan(numFolds, 5);

foldSamplingFactors = ...
    nan(numFolds, 5);

foldMetrics = table( ...
    'Size', ...
        [numFolds 5], ...
    'VariableTypes', ...
        {'double','double','double','double','double'}, ...
    'VariableNames', ...
        {'Fold', ...
         'Accuracy', ...
         'QWK', ...
         'MacroRecall', ...
         'Grade4Recall'});

miniBatch = ...
    pickMiniBatchSize( ...
        g.AvailableMemory);

fprintf( ...
    '\nInitial mini-batch size: %d\n', ...
    miniBatch);

% =========================================================================
% TRAIN FOLDS
% =========================================================================

for fold = 1:numFolds

    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('Fold %d / %d\n', fold, numFolds);
    fprintf('============================================================\n');

    % ---------------------------------------------------------------------
    % Outer fold
    % ---------------------------------------------------------------------

    trainIdx = ...
        training(cv, fold);

    valIdx = ...
        test(cv, fold);

    foldTrainingRows = ...
        find(trainIdx);

    % ---------------------------------------------------------------------
    % Inner 15%% validation split
    % ---------------------------------------------------------------------

    inner = cvpartition( ...
        labels(trainIdx), ...
        'HoldOut', ...
        0.15);

    innerTrainRows = ...
        foldTrainingRows( ...
            training(inner));

    earlyStopRows = ...
        foldTrainingRows( ...
            test(inner));

    % ---------------------------------------------------------------------
    % Actual inner-training class counts
    % ---------------------------------------------------------------------

    trainGrades = ...
        rawGrades(innerTrainRows);

    foldCounts = ...
        accumarray( ...
            trainGrades + 1, ...
            1, ...
            [5 1], ...
            @sum, ...
            0);

    if any(foldCounts == 0)

        error( ...
            'Fold %d contains a class with zero training samples.', ...
            fold);

    end

    % ---------------------------------------------------------------------
    % SQUARE-ROOT BALANCING
    %
    % target = sqrt(count * maximumCount)
    %
    % This gives moderate augmentation-based balancing.
    %
    % Example:
    %
    % count = [77 11 77 42 28]
    %
    % target ~= [77 29 77 57 46]
    %
    % This is substantially less aggressive than forcing every class
    % to the largest class.
    % ---------------------------------------------------------------------

    maxCount = ...
        max(foldCounts);

    targetCounts = ...
        round( ...
            sqrt( ...
                double(foldCounts) * ...
                double(maxCount)));

    targetCounts = ...
        max( ...
            targetCounts, ...
            foldCounts);

    samplingFactors = ...
        targetCounts ./ ...
        foldCounts;

    foldSamplingTargets(fold, :) = ...
        targetCounts(:)';

    foldSamplingFactors(fold, :) = ...
        samplingFactors(:)';

    fprintf( ...
        'Fold %d original counts, grades 0..4: %s\n', ...
        fold, ...
        mat2str(foldCounts'));

    fprintf( ...
        'Fold %d augmented targets, grades 0..4: %s\n', ...
        fold, ...
        mat2str(targetCounts'));

    fprintf( ...
        'Fold %d sampling factors: %s\n', ...
        fold, ...
        mat2str(samplingFactors, 2));

    % ---------------------------------------------------------------------
    % Build repeated-row training set.
    %
    % IMPORTANT:
    % These are row repetitions, not saved duplicate images.
    %
    % augmentedImageDatastore will apply random transformations when
    % each occurrence is read.
    % ---------------------------------------------------------------------

    balancedRows = ...
        balanceTrainingRows( ...
            innerTrainRows, ...
            rawGrades, ...
            targetCounts);

    fprintf( ...
        'Training rows after square-root balancing: %d\n', ...
        numel(balancedRows));

    % ---------------------------------------------------------------------
    % Training datastore
    % ---------------------------------------------------------------------

    trainDS = imageDatastore( ...
        cachedPaths(balancedRows), ...
        'Labels', ...
            labels(balancedRows), ...
        'ReadFcn', ...
            readCached);

    trainDS.ReadSize = ...
        miniBatch;

    % ---------------------------------------------------------------------
    % Early stopping datastore
    % ---------------------------------------------------------------------

    earlyStopDS = ...
        subset( ...
            imds, ...
            earlyStopRows);

    valDS = ...
        subset( ...
            imds, ...
            find(valIdx));

    % ---------------------------------------------------------------------
    % Augmented training datastore
    %
    % Every repeated minority example receives randomized transformations
    % when read.
    % ---------------------------------------------------------------------

    trainAug = ...
        augmentedImageDatastore( ...
            inputSize(1:2), ...
            trainDS, ...
            'DataAugmentation', ...
            augmenter);

    trainAug.MiniBatchSize = ...
        miniBatch;

    earlyStopAug = ...
        augmentedImageDatastore( ...
            inputSize(1:2), ...
            earlyStopDS);

    earlyStopAug.MiniBatchSize = ...
        miniBatch;

    stepsPerEpoch = ...
        max( ...
            1, ...
            ceil( ...
                numel(balancedRows) / ...
                miniBatch));

    % ---------------------------------------------------------------------
    % Checkpoint directory
    % ---------------------------------------------------------------------

    ckptDir = ...
        fullfile( ...
            modelDir, ...
            sprintf( ...
                'checkpoints_fold-%d', ...
                fold));

    if ~isfolder(ckptDir)
        mkdir(ckptDir);
    end

    % ---------------------------------------------------------------------
    % IMPORTANT:
    % NO CLASS WEIGHTS
    %
    % This experiment tests augmentation-based balancing by itself.
    % ---------------------------------------------------------------------

    lossFcn = ...
        'crossentropy';

    % ---------------------------------------------------------------------
    % TRAIN
    % ---------------------------------------------------------------------

    trained = false;

    batchTry = ...
        miniBatch;

    while ~trained

        net = ...
            buildGradingNetwork( ...
                inputSize, ...
                projectDir);

        options = ...
            makeGpuTrainOptions( ...
                batchTry, ...
                earlyStopAug, ...
                stepsPerEpoch, ...
                ckptDir);

        fprintf( ...
            'Training on GPU, MiniBatchSize %d, ~%d steps/epoch\n', ...
            batchTry, ...
            max( ...
                1, ...
                ceil( ...
                    numel(balancedRows) / ...
                    batchTry)));

        try

            net = ...
                trainnet( ...
                    trainAug, ...
                    net, ...
                    lossFcn, ...
                    options);

            trained = true;

            miniBatch = ...
                batchTry;

        catch err

            if batchTry > 2 && ...
                    isGpuMemoryError(err)

                nextBatch = ...
                    max( ...
                        2, ...
                        floor( ...
                            batchTry / 2));

                fprintf( ...
                    ['GPU out of memory at batch %d. ', ...
                     'Retrying with %d.\n'], ...
                    batchTry, ...
                    nextBatch);

                batchTry = ...
                    nextBatch;

                trainAug.MiniBatchSize = ...
                    batchTry;

                earlyStopAug.MiniBatchSize = ...
                    batchTry;

                reset(gpuDevice);

            else

                rethrow(err);

            end
        end
    end

    % ---------------------------------------------------------------------
    % Score outer validation fold
    % ---------------------------------------------------------------------

    scores = ...
        scoreNetwork( ...
            net, ...
            valDS, ...
            miniBatch);

    % ---------------------------------------------------------------------
    % Argmax prediction
    % ---------------------------------------------------------------------

    [~, scoreIndex] = ...
        max( ...
            scores, ...
            [], ...
            2);

    predLabels = ...
        categorical( ...
            string(scoreIndex - 1), ...
            classNames);

    truth = ...
        rawGrades(valIdx);

    predicted = ...
        str2double( ...
            string(predLabels));

    % ---------------------------------------------------------------------
    % Store OOF predictions
    % ---------------------------------------------------------------------

    oofScores(valIdx, :) = ...
        scores;

    oofPredictions(valIdx) = ...
        predicted;

    % ---------------------------------------------------------------------
    % Fold metrics
    % ---------------------------------------------------------------------

    metrics = ...
        gradeMetrics( ...
            truth, ...
            predicted);

    foldMetrics{fold, :} = ...
        [ ...
            fold, ...
            metrics.accuracy, ...
            metrics.qwk, ...
            metrics.macroRecall, ...
            metrics.grade4Recall];

    fprintf( ...
        ['Fold %d | accuracy %.3f | QWK %.3f | ', ...
         'macro recall %.3f | grade-4 recall %.3f\n'], ...
        fold, ...
        metrics.accuracy, ...
        metrics.qwk, ...
        metrics.macroRecall, ...
        metrics.grade4Recall);

    % ---------------------------------------------------------------------
    % Save fold model
    % ---------------------------------------------------------------------

    foldModelPath = ...
        fullfile( ...
            modelDir, ...
            sprintf( ...
                'fold-%d.mat', ...
                fold));

    save( ...
        foldModelPath, ...
        'net', ...
        'inputSize', ...
        'classNames', ...
        'backboneName', ...
        'fold', ...
        'foldCounts', ...
        'targetCounts', ...
        'samplingFactors', ...
        '-v7.3');

    fprintf( ...
        'Saved %s\n', ...
        foldModelPath);

    clear net;

end

