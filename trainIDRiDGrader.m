function scores = ...
    scoreNetwork( ...
        net, ...
        ds, ...
        miniBatch)

numImages = ...
    numel(ds.Files);

scores = ...
    zeros( ...
        numImages, ...
        5, ...
        'single');

sample = ...
    single( ...
        readimage( ...
            ds, ...
            1));

H = ...
    size(sample, 1);

W = ...
    size(sample, 2);

hasSoftmax = ...
    any( ...
        arrayfun( ...
            @(l) ...
                isa( ...
                    l, ...
                    'nnet.cnn.layer.SoftmaxLayer'), ...
            net.Layers));

useSoftmax = ...
    ~hasSoftmax;

for startIdx = ...
        1:miniBatch:numImages

    stopIdx = ...
        min( ...
            startIdx + miniBatch - 1, ...
            numImages);

    nb = ...
        stopIdx - startIdx + 1;

    batch = ...
        zeros( ...
            H, ...
            W, ...
            3, ...
            nb, ...
            'single');

    for j = 1:nb

        batch(:, :, :, j) = ...
            single( ...
                readimage( ...
                    ds, ...
                    startIdx + j - 1));

    end

    X = ...
        dlarray( ...
            gpuArray(batch), ...
            'SSCB');

    out = ...
        predict( ...
            net, ...
            X);

    if useSoftmax
        out = softmax(out);
    end

    P = ...
        reshape( ...
            gather( ...
                extractdata(out)), ...
            5, []);

    scores( ...
        startIdx:stopIdx, :) = ...
        P';

end

end

% =========================================================================

function m = ...
    gradeMetrics( ...
        truth, ...
        predicted)

valid = ...
    isfinite(predicted);

truth = ...
    truth(valid);

predicted = ...
    predicted(valid);

cm = ...
    confusionmat( ...
        truth, ...
        predicted, ...
        'Order', ...
        0:4);

recall = ...
    diag(cm) ./ ...
    max( ...
        sum(cm, 2), ...
        1);

precision = ...
    diag(cm) ./ ...
    max( ...
        sum(cm, 1)', ...
        1);

f1 = ...
    2 .* precision .* recall ./ ...
    max( ...
        precision + recall, ...
        eps);

n = ...
    sum(cm(:));

[r, c] = ...
    ndgrid( ...
        0:4, ...
        0:4);

w = ...
    (r - c).^2 / 16;

observed = ...
    sum( ...
        w(:) .* cm(:)) / ...
    max(n, 1);

expectedCounts = ...
    sum(cm, 2) * ...
    sum(cm, 1) / ...
    max(n, 1);

expected = ...
    sum( ...
        w(:) .* expectedCounts(:)) / ...
    max(n, 1);

m.accuracy = ...
    sum(diag(cm)) / ...
    max(n, 1);

m.qwk = ...
    1 - observed / ...
    max(expected, eps);

m.macroRecall = ...
    mean(recall);

m.macroF1 = ...
    mean(f1);

m.grade4Recall = ...
    recall(5);

m.grade4Precision = ...
    precision(5);

m.grade4F1 = ...
    f1(5);

end

% =========================================================================

function thresholds = ...
    fitGradeThresholds( ...
        expectedGrades, ...
        truth)

% Fit ordinal thresholds ONLY on OOF predictions.

thresholds = ...
    0.5:1:3.5;

basePred = ...
    decodeGrades( ...
        expectedGrades, ...
        thresholds);

best = ...
    gradeMetrics( ...
        truth, ...
        basePred).qwk;

for pass = 1:5

    changed = false;

    for j = 1:4

        lo = ...
            -0.25;

        hi = ...
            4.25;

        if j > 1

            lo = ...
                thresholds(j - 1) + ...
                0.02;

        end

        if j < 4

            hi = ...
                thresholds(j + 1) - ...
                0.02;

        end

        candidates = ...
            linspace( ...
                lo, ...
                hi, ...
                61);

        for candidate = candidates

            trial = ...
                thresholds;

            trial(j) = ...
                candidate;

            trialPred = ...
                decodeGrades( ...
                    expectedGrades, ...
                    trial);

            score = ...
                gradeMetrics( ...
                    truth, ...
                    trialPred).qwk;

            if score > best

                best = ...
                    score;

                thresholds = ...
                    trial;

                changed = true;

            end
        end
    end

    if ~changed
        break;
    end
end

end

% =========================================================================

function predicted = ...
    decodeGrades( ...
        expectedGrades, ...
        thresholds)

predicted = ...
    zeros(size(expectedGrades));

for threshold = thresholds

    predicted = ...
        predicted + ...
        (expectedGrades > threshold);

end

end

% =========================================================================

function [ ...
        bestThreshold, ...
        bestPred, ...
        bestMetrics] = ...
    fitGrade4ProbThreshold( ...
        scores, ...
        expectedGrades, ...
        truth, ...
        thresholds)

% Fit grade-4 probability threshold ONLY on OOF predictions.
%
% Grade 4 override:
%   argmax == 4
%   OR
%   P(grade 4) >= threshold
%
% Objective:
%   30%% QWK
%   20%% referable sensitivity
%   20%% grade-4 F1
%   30%% macro F1

[~, idx] = ...
    max( ...
        scores, ...
        [], ...
        2);

argmaxPred = ...
    idx - 1;

ordinalPred = ...
    decodeGrades( ...
        expectedGrades, ...
        thresholds);

candidateThresholds = ...
    0:0.005:1;

bestScore = ...
    -Inf;

bestThreshold = ...
    0.5;

bestPred = ...
    ordinalPred;

bestMetrics = ...
    gradeMetrics( ...
        truth, ...
        ordinalPred);

bestMetrics.referableSensitivity = ...
    calculateReferableSensitivity( ...
        truth, ...
        ordinalPred);

bestMetrics.compositeScore = ...
    -Inf;

for t = candidateThresholds

    pred = ...
        ordinalPred;

    forceGrade4 = ...
        (argmaxPred == 4) | ...
        (scores(:,5) >= t);

    pred(forceGrade4) = ...
        4;

    m = ...
        gradeMetrics( ...
            truth, ...
            pred);

    cm = ...
        confusionmat( ...
            truth, ...
            pred, ...
            'Order', ...
            0:4);

    % -------------------------------------------------------------
    % Grade-4 metrics
    % -------------------------------------------------------------

    grade4TP = ...
        cm(5,5);

    grade4FN = ...
        sum(cm(5,1:4));

    grade4FP = ...
        sum(cm(1:4,5));

    grade4Recall = ...
        grade4TP / ...
        max( ...
            grade4TP + grade4FN, ...
            1);

    grade4Precision = ...
        grade4TP / ...
        max( ...
            grade4TP + grade4FP, ...
            1);

    grade4F1 = ...
        2 * grade4Precision * ...
        grade4Recall / ...
        max( ...
            grade4Precision + ...
            grade4Recall, ...
            eps);

    % -------------------------------------------------------------
    % Referable sensitivity
    % -------------------------------------------------------------

    refSens = ...
        calculateReferableSensitivity( ...
            truth, ...
            pred);

    % -------------------------------------------------------------
    % Composite score
    % -------------------------------------------------------------

    composite = ...
          0.30 * m.qwk ...
        + 0.20 * refSens ...
        + 0.20 * grade4F1 ...
        + 0.30 * m.macroF1;

    if composite > bestScore + 1e-12 || ...
            ( ...
                abs(composite - bestScore) <= 1e-12 && ...
                t > bestThreshold)

        bestScore = ...
            composite;

        bestThreshold = ...
            t;

        bestPred = ...
            pred;

        bestMetrics = ...
            m;

        bestMetrics.grade4Recall = ...
            grade4Recall;

        bestMetrics.grade4Precision = ...
            grade4Precision;

        bestMetrics.grade4F1 = ...
            grade4F1;

        bestMetrics.referableSensitivity = ...
            refSens;

        bestMetrics.compositeScore = ...
            composite;

    end
end

end

% =========================================================================

function sensitivity = ...
    calculateReferableSensitivity( ...
        truth, ...
        predicted)

trueReferable = ...
    truth >= 2;

predReferable = ...
    predicted >= 2;

TP = ...
    sum( ...
        trueReferable & ...
        predReferable);

FN = ...
    sum( ...
        trueReferable & ...
        ~predReferable);

sensitivity = ...
    TP / ...
    max( ...
        TP + FN, ...
        1);

end