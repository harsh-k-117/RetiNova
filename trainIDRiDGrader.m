function [net, backboneName] = ...
    buildGradingNetwork( ...
        inputSize, ...
        projectDir)

net = [];
backboneName = '';

% -------------------------------------------------------------------------
% MATLAB pretrained networks
% -------------------------------------------------------------------------

if exist('imagePretrainedNetwork', 'file') == 2

    modelNames = ...
        ["efficientnetb0", "resnet50"];

    for i = 1:numel(modelNames)

        modelName = ...
            modelNames(i);

        try

            net = ...
                imagePretrainedNetwork( ...
                    modelName, ...
                    'NumClasses', ...
                    5);

            net = ...
                replaceImageInput( ...
                    net, ...
                    inputSize);

            backboneName = ...
                char(modelName);

            return;

        catch err

            fprintf( ...
                '%s not used: %s\n', ...
                modelName, ...
                err.message);

            net = [];

        end
    end
end

% -------------------------------------------------------------------------
% ONNX fallback
% -------------------------------------------------------------------------

onnxPath = ...
    fullfile( ...
        projectDir, ...
        'data', ...
        'efficientnet_b0_regression_512px.onnx');

if ~isfile(onnxPath)

    error([ ...
        'Install the EfficientNet-B0 or ResNet-50 support package, ', ...
        'or place efficientnet_b0_regression_512px.onnx under data/.']);

end

baseNet = ...
    importNetworkFromONNX( ...
        onnxPath);

lgraph = ...
    layerGraph(baseNet);

head = ...
    fullyConnectedLayer( ...
        5, ...
        'Name', ...
            'grade_head', ...
        'WeightLearnRateFactor', ...
            10, ...
        'BiasLearnRateFactor', ...
            10, ...
        'WeightsInitializer', ...
            'he');

lgraph = ...
    replaceLayer( ...
        lgraph, ...
        'x_backbone_classifie', ...
        head);

lgraph = ...
    addLayers( ...
        lgraph, ...
        softmaxLayer( ...
            'Name', ...
                'grade_softmax'));

lgraph = ...
    connectLayers( ...
        lgraph, ...
        'grade_head', ...
        'grade_softmax');

net = ...
    dlnetwork(lgraph);

backboneName = ...
    'efficientnet_b0_onnx';

end

% =========================================================================

function net = ...
    replaceImageInput( ...
        net, ...
        inputSize)

lgraph = ...
    layerGraph(net);

layers = ...
    lgraph.Layers;

isInput = ...
    arrayfun( ...
        @(layer) ...
            isa( ...
                layer, ...
                'nnet.cnn.layer.ImageInputLayer'), ...
        layers);

if ~any(isInput)

    error( ...
        'No image input layer found.');

end

oldLayer = ...
    layers(find(isInput, 1));

newLayer = ...
    imageInputLayer( ...
        inputSize, ...
        'Name', ...
            oldLayer.Name, ...
        'Normalization', ...
            'none');

lgraph = ...
    replaceLayer( ...
        lgraph, ...
        oldLayer.Name, ...
        newLayer);

net = ...
    dlnetwork(lgraph);

end

